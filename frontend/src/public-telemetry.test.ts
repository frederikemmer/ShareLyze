import { afterEach,it,expect,vi } from "vitest";
afterEach(() => {vi.useRealTimers();vi.unstubAllGlobals();vi.resetModules();});
it("reports view/context/navigation/resource quality without raw URL secrets and stops cleanly",async () => {
  vi.useFakeTimers();
  const calls:any[]=[];let schemeChanged:()=>void=()=>{};let callback:(list:any)=>void=()=>{};
  vi.stubGlobal("fetch",vi.fn((_url,options) => {calls.push(options);return Promise.resolve(new Response("{}"));}));
  vi.stubGlobal("location",{origin:"https://share.example",href:"https://share.example/share/photo",search:"?utm_source=card&utm_medium=qr&password=never-store"});
  vi.stubGlobal("navigator",{maxTouchPoints:5});
  vi.stubGlobal("matchMedia",() => ({matches:true,addEventListener:(_name:string,handler:()=>void) => {schemeChanged=handler;},removeEventListener:vi.fn()}));
  vi.stubGlobal("window",{addEventListener:vi.fn(),removeEventListener:vi.fn()});
  vi.stubGlobal("performance",{getEntriesByType:() => [{loadEventEnd:100,startTime:0,responseStart:20,domContentLoadedEventEnd:80,responseStatus:200,transferSize:500}]});
  const disconnect=vi.fn();
  vi.stubGlobal("PerformanceObserver",class {constructor(cb:(list:any)=>void) {callback=cb;}observe() {}disconnect=disconnect;});
  const module=await import("./public-telemetry");
  expect(module.publicCampaignQuery()).toBe("utm_source=card&utm_medium=qr");
  expect(module.withPublicVisit("/file?path=x","token")).toBe("/file?path=x&visit=token");
  let view:"grid"|"list"="grid";
  const telemetry=module.startPublicTelemetry("photo","test-token",() => view);
  expect(JSON.parse(calls[0].body).client).toMatchObject({touchPoints:5,colorScheme:"dark",view:"grid"});
  view="list";telemetry.viewChanged();schemeChanged();
  await vi.runOnlyPendingTimersAsync();
  const name="https://share.example/api/public/photo/items/f/preview?path=folder/picture.jpg&password=never-store";
  callback({getEntries:() => [{name,startTime:10,duration:30,responseStart:20,responseStatus:200,transferSize:500}]});
  callback({getEntries:() => [{name,startTime:10,duration:30,responseStart:20,responseStatus:200,transferSize:500}]});
  module.reportPublicResourceError(name);
  module.reportPublicResourceError("https://other.example/file");
  const bodies=calls.map(options => JSON.parse(options.body));
  expect(bodies.filter(body => body.kind==="navigation")).toHaveLength(1);
  expect(bodies.filter(body => body.kind==="resource")).toHaveLength(1);
  expect(bodies.filter(body => body.kind==="view_change")[0].client.view).toBe("list");
  expect(bodies.find(body => body.kind==="resource_error")).toMatchObject({resource:"preview",itemId:"f",path:"folder/picture.jpg"});
  expect(JSON.stringify(bodies)).not.toContain("never-store");
  const previous=calls.length;
  telemetry.stop();telemetry.viewChanged();schemeChanged();
  expect(calls).toHaveLength(previous);
  expect(disconnect).toHaveBeenCalled();
  expect(calls[0].signal.aborted).toBe(true);
});
